"""Studio -> Tauri IPC -> COSMIC config, using the owned nested compositor.

AT-SPI actions exercise the real UI; this does not claim native keyboard coverage.
Close only the owned app before sampling compositor pixels behind its window.
"""
import gi
gi.require_version('Atspi', '2.0')
from gi.repository import Atspi, GLib
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time


def verify_ui(root, env, capture_pixels, children, log, prepare_case):
    assert env['XDG_CURRENT_DESKTOP'] == 'COSMIC'
    assert env['WAYLAND_DISPLAY'] != 'deskmorph-lab'
    assert env['XDG_CONFIG_HOME'] == str(root / 'config')
    repo = Path(__file__).resolve().parents[1]
    binary = Path(env.get('DESKMORPH_LAB_BINARY', repo / 'src-tauri/target/agent/debug/deskmorph'))
    images = root / 'ui-images'; images.mkdir()
    for name in ('pink', 'blue'): (images / (name + '.png')).write_bytes((root / (name + '.png')).read_bytes())
    entry = root / 'config/cosmic/com.system76.CosmicBackground/v1/all'
    def source(output="all"):
        # Observation only; production editing uses the RON parser. Fixture paths
        # are generated by the lab and do not contain RON-specific escapes.
        target = entry if output == "all" else entry.with_name("output." + output)
        if not target.exists(): return None
        match = re.search(r'source:\s*Path\(("(?:[^"\\]|\\.)*")\)', target.read_text())
        return json.loads(match[1]) if match else None
    def wait(predicate, message):
        deadline = time.monotonic() + 15
        while time.monotonic() < deadline:
            try: value = predicate()
            except GLib.Error as error:
                if 'does not exist' not in str(error): raise
                value = None  # transient AT-SPI object removal during startup
            if value: return value
            time.sleep(.1)
        raise AssertionError(message)
    def descendants(node):
        yield node
        for index in range(node.get_child_count()):
            child = node.get_child_at_index(index)
            if child: yield from descendants(child)
    def stop(process):
        if process.poll() is None:
            process.terminate()
            try: process.wait(timeout=5)
            except subprocess.TimeoutExpired: process.kill(); process.wait(timeout=5)
    observations = []
    # Missing user entry is an actual runtime condition. Observe capability
    # without materializing config, then create it through the production UI.

    for language in ('vi', 'en'):
        prepare_case(language)
        if language == 'en': assert capture_pixels([52, 86, 120], 'en-seeded-default-blue')
        config_home = root / ('cosmic-ui-' + language)
        config_file = config_home / 'com.ducthanhdev.deskmorph/config.json'
        config_file.parent.mkdir(parents=True)
        config = json.loads((repo / 'src/config/defaults.json').read_text())
        config.update(language=language, enabled=False, reduceMotion=True,
            wallpaperFolders=[str(images)], wallpaperScheduleEnabled=False)
        config_file.write_text(json.dumps(dict(schemaVersion=1, revision=0, config=config)))
        app_env = dict(env, DESKMORPH_CONFIG_HOME=str(config_home), WEBKIT_DISABLE_DMABUF_RENDERER='1')
        labels = dict(tab='Hình nền', apply='Áp dụng', retry='Thử lại', shuffle='Đổi ngẫu nhiên', done='Đã áp dụng hình nền.') if language == 'vi' else dict(tab='Wallpapers', apply='Apply', retry='Retry', shuffle='Shuffle now', done='Wallpaper applied.')
        def launch():
            process = subprocess.Popen([str(binary)], env=app_env, stdout=log, stderr=log)
            children.append(process)
            app = wait(lambda: next((a for a in descendants(Atspi.get_desktop(0))
                if a.get_role_name() == 'application' and a.get_process_id() == process.pid), None), 'COSMIC Studio accessibility did not appear')
            def find(name):
                return next((n for n in descendants(app) if n.get_name() == name and n.get_role_name() in ('button', 'toggle button')), None)
            def action(name):
                node = wait(lambda: find(name), 'Missing COSMIC Studio control: ' + name)
                assert node.get_state_set().contains(Atspi.StateType.ENABLED), 'Disabled COSMIC control: ' + name
                assert node.get_action_iface().do_action(0), 'AT-SPI action failed: ' + name
            action(labels['tab'])
            wait(lambda: find(labels['apply'] + ' pink.png'), 'COSMIC wallpaper scan did not finish')
            def contains(needle):
                for node in descendants(app):
                    if node.get_name() == needle: return True
                    if node.get_role_name() in ('text', 'static', 'paragraph', 'status bar', 'label'):
                        text = node.get_text_iface()
                        if text and needle in Atspi.Text.get_text(text, 0, -1): return True
                return False
            return process, find, action, lambda: contains(labels['done']), contains
        process, find, action, completed, contains = launch()
        try:
            if language == 'vi': assert not entry.exists(), 'Read-only capability probe created config'
            action(labels['apply'] + ' pink.png')
            wait(lambda: source() == str(images / 'pink.png'), 'UI Apply did not write COSMIC source')
            wait(completed, 'UI Apply did not report completed IPC')
            if language == 'en':
                assert source('WINIT-0') == str(images / 'pink.png')
                assert capture_pixels(None, 'en-ui-studio')
        finally: stop(process)
        time.sleep(.5)
        assert capture_pixels([209, 55, 105], language + '-ui-apply'), 'UI Apply did not display pink in COSMIC'
        process, find, action, completed, contains = launch()
        try:
            blue = images / 'blue.png'; blue.unlink()
            action(labels['apply'] + ' blue.png')
            wait(lambda: find(labels['retry']), 'Missing-file Apply did not offer Retry')
            assert source() == str(images / 'pink.png'), 'Failed Apply changed COSMIC source'
            blue.write_bytes((root / 'blue.png').read_bytes())
            action(labels['retry'])
            wait(lambda: source() == str(blue), 'UI Retry did not write COSMIC source')
            wait(completed, 'UI Retry did not report completed IPC')
            if language == 'en': assert source('WINIT-0') == str(blue)
        finally: stop(process)
        time.sleep(.5)
        assert capture_pixels([52, 86, 120], language + '-ui-retry'), 'UI Retry did not display blue in COSMIC'
        process, find, action, completed, contains = launch()
        try:
            action(labels['shuffle'])
            wait(lambda: source() == str(images / 'pink.png'), 'Shuffle did not exclude current blue source')
            wait(completed, 'UI Shuffle did not report completed IPC')
            if language == 'en': assert source('WINIT-0') == str(images / 'pink.png')
        finally: stop(process)
        time.sleep(.5)
        assert capture_pixels([209, 55, 105], language + '-ui-shuffle'), 'UI Shuffle did not display pink in COSMIC'
        saved = entry.read_text()
        for problem in ('invalid', 'read-only'):
            if problem == 'invalid': entry.write_text('invalid local override')
            else: entry.chmod(0o400)
            try:
                process, find, action, completed, contains = launch()
                try:
                    wait(lambda: (node := find(labels['apply'] + ' pink.png')) and not node.get_state_set().contains(Atspi.StateType.ENABLED), 'Unsafe config did not disable Apply')
                    message = ('Cấu hình hình nền không hợp lệ hoặc không thể đọc được; dữ liệu hiện có được giữ nguyên.' if language == 'vi' else 'Wallpaper configuration is invalid or unreadable; existing data is preserved.') if problem == 'invalid' else ('Thiết lập hình nền đang bị khóa chỉ đọc.' if language == 'vi' else 'Wallpaper settings are locked read-only.')
                    wait(lambda: contains(message), 'Missing localized capability reason for ' + problem)
                    assert entry.read_text() == ('invalid local override' if problem == 'invalid' else saved)
                finally: stop(process)
            finally:
                entry.chmod(0o600)
                entry.write_text(saved)
        observations.append(dict(language=language, applyPixelsVerified=True,
            createdMissingUserEntry=(language == "vi"),
            createdMissingPerOutputEntry=(language == "en"),
            ipcCompletionStatusObserved=True,
            invalidConfigDisabledAndPreserved=True, readOnlyConfigDisabledAndPreserved=True,
            missingFilePreservedPreviousSource=True, retryPixelsVerified=True,
            shuffleExcludedCurrentAndPixelsVerified=True, ownedAppExited=True,
            input='AT-SPI actions, actual app on nested COSMIC Wayland socket; no keyboard claim'))
    return dict(observations=observations, binarySha256=hashlib.sha256(binary.read_bytes()).hexdigest())
